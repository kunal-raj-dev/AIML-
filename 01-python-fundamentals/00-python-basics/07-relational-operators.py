# 07. Relational / Comparison Operators in Python
# Relational operators evaluate expressions and return a boolean (True / False).

x = 25
y = 18

print(f"x = {x}, y = {y}\n")
print(f"Equal to                 (x == y) : {x == y}")
print(f"Not equal to             (x != y) : {x != y}")
print(f"Greater than             (x > y)  : {x > y}")
print(f"Less than                (x < y)  : {x < y}")
print(f"Greater than or equal to (x >= y) : {x >= y}")
print(f"Less than or equal to    (x <= y) : {x <= y}")

# Chained comparisons
age = 22
print(f"\nIs 18 <= age <= 30? {18 <= age <= 30}")
