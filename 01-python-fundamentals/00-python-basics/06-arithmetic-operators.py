# 06. Arithmetic Operators in Python

a = 15
b = 4

print(f"a = {a}, b = {b}\n")
print(f"Addition        (a + b)  : {a + b}")
print(f"Subtraction     (a - b)  : {a - b}")
print(f"Multiplication  (a * b)  : {a * b}")
print(f"Division (float)(a / b)  : {a / b}")
print(f"Floor Division  (a // b) : {a // b}  (drops decimal part)")
print(f"Modulus/Remainder(a % b) : {a % b}   (remainder after division)")
print(f"Exponentiation  (a ** b) : {a ** b}  (15 raised to power 4)")
